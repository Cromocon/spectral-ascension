STATES = ["standby", "pulling_0", "pulling_1", "pulling_2", "arrow", "firework",
          "glass", "topaz", "amethyst", "citrine", "onyx", "moonstone"]


GEMCH = set("qrstmnopuvwxW")      # pixel di gemma della base: le sovrapposizioni (corda, freccia) non li coprono


class Top(list):
    """Griglia di sovrapposizione che copre anche i pixel di gemma del castone (giro 7: asta e razzo passano sopra la gemma)."""


def lay(*gs):
    """Sovrappone le griglie (i punti sono trasparenti); i pixel di gemma del castone della base restano visibili,
    salvo per le griglie Top (munizione e dettagli dell'utente), che li coprono."""
    out = [list(r) for r in gs[0]]
    for g in gs[1:]:
        for y, r in enumerate(g):
            for x, c in enumerate(r):
                if c != "." and (isinstance(g, Top) or out[y][x] not in GEMCH):
                    out[y][x] = c
    return ["".join(r) for r in out]


def big(g20):
    """La balestra 20x20 nella zona 12-31 del 32x32 (angolo in basso a destra): colonne 12-31, righe 12-31."""
    return ["." * 32] * 12 + ["." * 12 + r for r in g20]


# Giro 7: ritocchi dell'utente specifici di uno stato, applicati sopra tutto il resto (griglie sparse: x, y -> lettera).
# glass: la testa della freccia a gemma ha ombra e luce diverse e lascia vedere il topazio (s, t) del castone; a 20x20 un
# pixel del corpo (14,13) e' di bedrock chiaro (4) invece di 3. citrine 20x20: un pixel dell'asta (11,11) e' legno (A, come da giro 8 dell'utente).
PATCH16 = {"glass": {(3, 3): "I", (4, 3): "s", (3, 4): "s", (4, 4): "G"}}
PATCH20 = {"glass": {(2, 2): "I", (3, 2): "s", (2, 3): "s", (3, 3): "s", (4, 3): "t", (3, 4): "t", (4, 4): "t", (14, 13): "4"},
           "citrine": {(11, 11): "A"}}


def patch(cells, n):
    g = [["."] * n for _ in range(n)]
    for (x, y), c in cells.items():
        g[y][x] = c
    return Top("".join(r) for r in g)


def crossbow_overlays(state):
    """(sovrapposizioni 16x16, sovrapposizioni 20x20, palette della munizione) per lo stato: corda e munizione."""
    if state in ("standby", "pulling_0", "pulling_1", "pulling_2"):
        pull = {"standby": "standby", "pulling_0": "0", "pulling_1": "1", "pulling_2": "2"}[state]
        return [GRIDS[f"ST16_{pull}"]], [GRIDS[f"ST20_{pull}"]], {}
    s16, s20 = [GRIDS["ST16_L"]], [GRIDS["ST20_L"]]
    if state == "firework":
        return s16 + [Top(GRIDS["FW16"])], s20 + [Top(GRIDS["FW20"])], {}
    s16, s20 = s16 + [Top(GRIDS["AM16"])], s20 + [Top(GRIDS["AM20"])]
    if state in PATCH16:
        s16.append(patch(PATCH16[state], 16))
    if state in PATCH20:
        s20.append(patch(PATCH20[state], 20))
    return s16, s20, GEMS[state]


def palette(extra=None):
    p = dict(T.PAL)
    p.update({k: H.hexc(v) for k, v in AMMO.items()})
    if extra:
        p.update({k: H.hexc(v) for k, v in extra.items()})
    return p


def render(rows, pal):
    im = Image.new("RGBA", (len(rows[0]), len(rows)), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != ".":
                im.putpixel((x, y), pal[c])
    return im


def animate(base):
    """I 20 fotogrammi (griglie) di una base: fasi e gradini sono quelli del set T6."""
    ph = T.orange_phases(base)
    return [T.frame_grid(base, f, ph) for f in range(T.FRAMES)]


def items():
    """nome -> (fotogrammi come griglie, palette, riferimento glass crest)."""
    out = {}
    for name, key, ref in (("workstaff", "WS", "glass_crest_workstaff"),
                           ("ultra_greatsword", "GS", "glass_crest_ultra_greatsword")):
        out[name] = (animate(GRIDS[key + "16"]), palette(), ref + ".png")
        out[name + "_oversized"] = (animate(GRIDS[key + "32"]), palette(), ref + "_oversized.png")
    out["bident"] = (animate(GRIDS["BI16"]), palette(), "fractal_glass_crest_bident.png")
    out["bident_oversized"] = (animate(GRIDS["BI32"]), palette(), "fractal_glass_crest_bident_oversized.png")
    base16, base20 = animate(GRIDS["CB16"]), animate(GRIDS["CB20"])    # animazione sulla base comune, senza corda
    for st in STATES:
        o16, o20, extra = crossbow_overlays(st)
        fr16 = [lay(fr, *o16) for fr in base16]
        fr20 = [big(lay(fr, *o20)) for fr in base20]
        out[f"crossbow_{st}"] = (fr16, palette(extra), f"glass_crest_crossbow_{st}.png")
        out[f"crossbow_{st}_oversized"] = (fr20, palette(extra), f"glass_crest_crossbow_{st}_oversized.png")
    return out


