def ref(fname):
    p = os.path.join(REF, fname)
    return Image.open(p).convert("RGBA") if os.path.exists(p) else None


def alpha_set(im):
    return {(x, y) for y in range(im.height) for x in range(im.width) if im.getpixel((x, y))[3]}


def verifica(res):
    """Sagome contro il glass crest, sincronia dei 12 stati e coerenza di frame 0 / immagine ferma."""
    righe = []
    tutti = items()
    for n in ALL:
        if n.startswith("crossbow"):
            continue
        r = ref(tutti[n][2])
        a, b = alpha_set(res[n][0]), alpha_set(r)
        righe.append((n, len(a & b) / len(a | b)))
    # frame 0 = immagine ferma, 20 fotogrammi, mcmeta
    for n in ALL:
        strip = Image.open(os.path.join(OUT, f"t6_{n}_anim.png")).convert("RGBA")
        w = strip.width
        assert strip.height == w * T.FRAMES, n
        assert list(strip.crop((0, 0, w, w)).getdata()) == list(Image.open(os.path.join(OUT, f"t6_{n}.png")).convert("RGBA").getdata()), n
        assert T.mcmeta_ticks(os.path.join(OUT, f"t6_{n}_anim.png")) == T.FRAMETIME
    # sincronia: i fotogrammi dei 12 stati, tolte corda e munizione, coincidono con quelli dello stato scarico
    for suf, side in (("", 16), ("_oversized", 32)):
        sync = True
        ov = (lambda s: crossbow_overlays(s)[0 if side == 16 else 1])
        for st in STATES:
            for f in range(T.FRAMES):
                cur = res["crossbow_" + st + suf][f]
                base = res["crossbow_standby" + suf][f]
                cells = set()
                for g in ov(st) + ov("standby"):
                    off = (12, 12) if side == 32 else (0, 0)
                    cells |= {(x + off[0], y + off[1]) for y, rr in enumerate(g) for x, c in enumerate(rr) if c != "."}
                diff = {(x, y) for y in range(side) for x in range(side) if cur.getpixel((x, y)) != base.getpixel((x, y))}
                sync &= diff <= cells
        righe.append((f"sincronia dei 12 stati della balestra{' (oversized)' if suf else ''}", 1.0 if sync else 0.0))
    return righe


